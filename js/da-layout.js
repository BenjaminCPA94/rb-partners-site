/* Inner-page organisation: numbered sections, "on this page" rail, reassurance row, two-column closing block.
   Idempotent; runs once the page content (generated by the other scripts) is in place. */
(() => {
  const main = document.querySelector('main');
  if (!main || document.documentElement.hasAttribute('data-ed-home')) return;
  const en = (document.documentElement.lang || 'fr').slice(0, 2) === 'en';
  const T = en
    ? { on: 'On this page', call: 'Or call us:', a: ['One partner, directly', 'French & English', 'A complete view'] }
    : { on: 'Sur cette page', call: 'Ou appelez-nous :', a: ['Un associé en direct', 'Français & anglais', 'Une vision d’ensemble'] };
  const EXCLUDE = '.expertise-cta, .mission-final, .intl-final, .rb-related, .v4-booking, .rb-related__grid';
  let tries = 0;

  const build = () => {
    if (main.dataset.daLayout) return true;
    const secs = [...main.children].filter((s) => s.tagName === 'SECTION');
    const hero = secs[0];
    if (!hero || !/(mission-hero|seo-hero|cab-hero)/.test(hero.className)) return true;

    /* reassurance row, when the hero has no proof chips of its own */
    const inner = hero.querySelector(':scope > .container');
    if (inner && !inner.querySelector('[class*="proofs"], .intl-hero-proof, .da-assure')) {
      const ul = document.createElement('ul');
      ul.className = 'da-assure';
      ul.innerHTML = T.a.map((x) => `<li>${x}</li>`).join('');
      inner.appendChild(ul);
    }

    /* two-column closing blocks */
    main.querySelectorAll('.expertise-cta > .container').forEach((c) => {
      if (c.querySelector('.da-cta-side')) return;
      const kids = [...c.children].filter((k) => !k.matches('h2, .eyebrow, script, style'));
      if (!c.querySelector('h2') || !kids.length) return;
      const side = document.createElement('div');
      side.className = 'da-cta-side';
      kids.forEach((k) => side.appendChild(k));
      if (!c.querySelector('a[href^="tel:"]')) {
        const p = document.createElement('p');
        p.className = 'da-cta-phone';
        p.innerHTML = `${T.call} <a href="tel:+33761534670">07 61 53 46 70</a>`;
        side.appendChild(p);
      }
      c.appendChild(side);
      c.classList.add('da-cta-split');
    });

    /* numbered sections + rail */
    const body = secs.slice(1).filter((s) => !s.matches(EXCLUDE));
    const eligible = body.filter((s) => s.querySelector('.eyebrow') || s.classList.contains('sc-section'));
    if (eligible.length < 3) {
      if (tries++ < 6) return false;
      main.dataset.daLayout = 'none';
      return true;
    }
    const first = eligible[0], last = eligible[eligible.length - 1];
    const range = body.slice(body.indexOf(first), body.indexOf(last) + 1);
    range.forEach((s) => s.classList.add('da-sec'));

    const items = [];
    eligible.forEach((s, i) => {
      const n = String(i + 1).padStart(2, '0');
      if (!s.id) s.id = `da-s${i + 1}`;
      const eb = s.querySelector('.eyebrow');
      const h2 = s.querySelector('h2');
      const label = (eb && eb.textContent.trim()) || (h2 && h2.textContent.trim()) || n;
      if (eb) eb.dataset.n = n;
      items.push({ id: s.id, n, label, el: s });
    });

    const rail = document.createElement('aside');
    rail.className = 'da-rail';
    rail.setAttribute('aria-label', T.on);
    rail.innerHTML = `<div class="da-rail__in"><p class="da-rail__title">${T.on}</p><ol>${items.map((it) => `<li><a href="#${it.id}"><span>${it.n}</span>${it.label.replace(/</g, '&lt;')}</a></li>`).join('')}</ol></div>`;
    main.appendChild(rail);
    main.classList.add('da-ruled');
    main.dataset.daLayout = 'rail';

    const place = () => {
      const top = first.offsetTop;
      rail.style.top = `${top}px`;
      rail.style.height = `${last.offsetTop + last.offsetHeight - top}px`;
    };
    place();
    if ('ResizeObserver' in window) new ResizeObserver(place).observe(main);
    window.addEventListener('resize', place);

    const links = [...rail.querySelectorAll('a')];
    if ('IntersectionObserver' in window) {
      const io = new IntersectionObserver((entries) => {
        entries.forEach((e) => {
          if (!e.isIntersecting) return;
          links.forEach((a) => a.classList.toggle('is-active', a.getAttribute('href') === `#${e.target.id}`));
        });
      }, { rootMargin: '-35% 0px -60% 0px' });
      items.forEach((it) => io.observe(it.el));
    }
    return true;
  };

  const start = () => { if (!build()) { const t = setInterval(() => { if (build()) clearInterval(t); }, 350); } };
  if (document.readyState === 'complete') setTimeout(start, 250); else window.addEventListener('load', () => setTimeout(start, 250));
})();
