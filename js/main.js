// Call dropdown
const callToggle = document.getElementById('call-toggle');
const callPanel = document.getElementById('call-panel');

if (callToggle && callPanel) {
  const closeCallPanel = () => {
    callPanel.classList.remove('is-open');
    callToggle.setAttribute('aria-expanded', 'false');
  };
  callToggle.addEventListener('click', (e) => {
    e.stopPropagation();
    const isOpen = callPanel.classList.toggle('is-open');
    callToggle.setAttribute('aria-expanded', String(isOpen));
  });
  document.addEventListener('click', (e) => {
    if (!callPanel.contains(e.target) && e.target !== callToggle) closeCallPanel();
  });
  document.addEventListener('keydown', (e) => { if (e.key === 'Escape') closeCallPanel(); });
}

// Scroll reveal animations
// The homepage already has hand-placed reveal classes. Internal pages are
// enhanced automatically so their sections build progressively as the user scrolls.
const prefersReducedMotion = window.matchMedia?.('(prefers-reduced-motion: reduce)').matches;
const isHomepage = Boolean(document.querySelector('main#top .hero'));

const observer = prefersReducedMotion ? null : new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (entry.isIntersecting) {
      entry.target.classList.add('is-visible');
      observer.unobserve(entry.target);
    }
  });
}, { threshold: 0.05, rootMargin: '0px 0px 8% 0px' });

const observeReveal = (el) => {
  if (el.dataset.rbRevealObserved === 'true') return;
  el.dataset.rbRevealObserved = 'true';
  if (prefersReducedMotion) {
    el.style.transitionDelay = '0ms';
    el.classList.add('is-visible');
    return;
  }
  observer?.observe(el);
};

const addProgressiveReveals = () => {
  if (!isHomepage) {
    document.querySelectorAll('main > section').forEach((section) => {
      const roots = section.querySelectorAll(':scope > .container, :scope > [class*="__inner"]');

      roots.forEach((root) => {
        let order = 0;
        [...root.children].forEach((child) => {
          if (child.matches('script, style')) return;

          const isCollection = child.children.length > 1 && /grid|list|cards|proofs|actions/i.test(child.className || '');
          const targets = isCollection ? [...child.children] : [child];

          targets.forEach((target) => {
            if (!target.classList.contains('reveal')) target.classList.add('reveal');
            if (!target.dataset.rbAutoReveal) {
              target.dataset.rbAutoReveal = 'true';
              target.style.transitionDelay = `${Math.min(order * 70, 280)}ms`;
            }
            order += 1;
          });
        });
      });
    });
  }

  document.querySelectorAll('.reveal').forEach(observeReveal);
};

addProgressiveReveals();
document.addEventListener('rb:content-upgraded', () => {
  // Run on the next frame so dynamically inserted cards are measurable before observing them.
  requestAnimationFrame(addProgressiveReveals);
});

// Contact form — submits the lead by email via FormSubmit (formsubmit.co), a
// zero-backend relay: the first real submission triggers a one-time
// confirmation link sent to contact@meyvin.fr that must be clicked to
// activate delivery. Falls back to a pre-filled mailto: draft if the
// request fails (offline, relay down, confirmation not yet done), so a
// lead is never silently lost.
const form = document.getElementById('contact-form');
const status = document.getElementById('form-status');
if (form) {
  form.addEventListener('submit', async (e) => {
    e.preventDefault();
    if (!form.checkValidity()) { form.reportValidity(); return; }
    const data = new FormData(form);
    const lang = window.rbI18n?.getLang?.() || document.documentElement.lang || 'fr';
    const company = data.get('company') === 'etrangere'
      ? (lang === 'en' ? 'Foreign company / France market entry' : 'Société étrangère / implantation en France')
      : (lang === 'en' ? 'French company' : 'Société française');
    const subject = lang === 'en' ? 'Contact request — Meyvin' : 'Demande de contact — Meyvin';

    const submitBtn = form.querySelector('button[type="submit"]');
    const fallbackToMailto = () => {
      const body = lang === 'en'
        ? `Name: ${data.get('name')}\nEmail: ${data.get('email')}\nCompany: ${company}\n\nMessage:\n${data.get('message')}`
        : `Nom : ${data.get('name')}\nEmail : ${data.get('email')}\nSociété : ${company}\n\nMessage :\n${data.get('message')}`;
      status.textContent = window.rbI18n ? window.rbI18n.get('form.fallback') : 'Votre messagerie va s’ouvrir avec votre demande préremplie.';
      window.location.href = `mailto:contact@meyvin.fr?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
    };

    if (submitBtn) submitBtn.disabled = true;
    try {
      const res = await fetch('https://formsubmit.co/ajax/contact@meyvin.fr', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', Accept: 'application/json' },
        body: JSON.stringify({
          name: data.get('name'),
          email: data.get('email'),
          company,
          message: data.get('message'),
          _subject: subject,
          _template: 'table',
          _captcha: 'false',
        }),
      });
      if (!res.ok) throw new Error('FormSubmit error');
      status.textContent = window.rbI18n ? window.rbI18n.get('form.success') : 'Merci, votre demande a bien été envoyée. Nous revenons vers vous rapidement.';
      form.reset();
    } catch (err) {
      fallbackToMailto();
    } finally {
      if (submitBtn) submitBtn.disabled = false;
    }
  });
}

