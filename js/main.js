// Escape closes the mobile menu and gives the focus back to its button
document.addEventListener('keydown', (e) => {
  if (e.key !== 'Escape') return;
  const b = document.getElementById('burger');
  const n = document.getElementById('nav');
  if (!b || !n || !n.classList.contains('is-open')) return;
  n.classList.remove('is-open');
  b.setAttribute('aria-expanded', 'false');
  b.focus();
});

// Call dropdown
const callToggle = document.getElementById('call-toggle');
const callPanel = document.getElementById('call-panel');

if (callToggle && callPanel) {
  const closeCallPanel = () => {
    callPanel.classList.remove('is-open');
    callToggle.setAttribute('aria-expanded', 'false');
  };
  callToggle.addEventListener('click', (e) => {
    e.stopPropagation();
    const isOpen = callPanel.classList.toggle('is-open');
    callToggle.setAttribute('aria-expanded', String(isOpen));
  });
  document.addEventListener('click', (e) => {
    if (!callPanel.contains(e.target) && e.target !== callToggle) closeCallPanel();
  });
  document.addEventListener('keydown', (e) => { if (e.key === 'Escape') closeCallPanel(); });
}

// Scroll reveal animations
// The homepage already has hand-placed reveal classes. Internal pages are
// enhanced automatically so their sections build progressively as the user scrolls.
const prefersReducedMotion = window.matchMedia?.('(prefers-reduced-motion: reduce)').matches;
const isHomepage = Boolean(document.querySelector('main#top .hero'));

const observer = prefersReducedMotion ? null : new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (entry.isIntersecting) {
      entry.target.classList.add('is-visible');
      observer.unobserve(entry.target);
    }
  });
}, { threshold: 0.05, rootMargin: '0px 0px 8% 0px' });

const observeReveal = (el) => {
  if (el.dataset.rbRevealObserved === 'true') return;
  el.dataset.rbRevealObserved = 'true';
  if (prefersReducedMotion) {
    el.style.transitionDelay = '0ms';
    el.classList.add('is-visible');
    return;
  }
  observer?.observe(el);
};

const addProgressiveReveals = () => {
  if (!isHomepage) {
    document.querySelectorAll('main > section').forEach((section) => {
      const roots = section.querySelectorAll(':scope > .container, :scope > [class*="__inner"]');

      roots.forEach((root) => {
        let order = 0;
        [...root.children].forEach((child) => {
          if (child.matches('script, style')) return;

          const isCollection = child.children.length > 1 && /grid|list|cards|proofs|actions/i.test(child.className || '');
          const targets = isCollection ? [...child.children] : [child];

          targets.forEach((target) => {
            if (!target.classList.contains('reveal')) target.classList.add('reveal');
            if (!target.dataset.rbAutoReveal) {
              target.dataset.rbAutoReveal = 'true';
              target.style.transitionDelay = `${Math.min(order * 70, 280)}ms`;
            }
            order += 1;
          });
        });
      });
    });
  }

  document.querySelectorAll('.reveal').forEach(observeReveal);
};

addProgressiveReveals();
document.addEventListener('rb:content-upgraded', () => {
  // Run on the next frame so dynamically inserted cards are measurable before observing them.
  requestAnimationFrame(addProgressiveReveals);
});

// Skip link: lets keyboard users jump past the header to the content.
(() => {
  const target = document.querySelector('main');
  if (!target || document.querySelector('.skip-link')) return;
  if (!target.id) target.id = 'contenu';
  target.setAttribute('tabindex', '-1');
  const lang = (document.documentElement.lang || 'fr') === 'en' ? 'en' : 'fr';
  const link = document.createElement('a');
  link.className = 'skip-link';
  link.href = `#${target.id}`;
  link.textContent = lang === 'en' ? 'Skip to content' : 'Aller au contenu';
  const style = document.createElement('style');
  style.textContent = '.skip-link{position:fixed;left:12px;top:-60px;z-index:100000;padding:12px 18px;border-radius:6px;background:#0b1d3a;color:#fff;font:600 .9rem Inter,sans-serif;text-decoration:none;transition:top .2s ease}.skip-link:focus{top:12px;outline:3px solid #9bb5ff;outline-offset:2px}main:focus{outline:none}';
  document.head.appendChild(style);
  document.body.prepend(link);
})();

// Contact form — submits the lead by email via FormSubmit (formsubmit.co), a
// zero-backend relay: the first real submission triggers a one-time
// confirmation link sent to contact@meyvin-experts.com that must be clicked to
// activate delivery. If the relay refuses (offline, relay down, activation
// not done) the visitor's mail app opens with the request pre-filled, and the
// page says plainly that the message still has to be sent from there.
const form = document.getElementById('contact-form');
const status = document.getElementById('form-status');
const PROJECTS = {
  fr: { suivi: 'Suivre ma comptabilité', creation: 'Créer mon entreprise', filiale: 'Accompagner ma filiale française', autre: 'Autre demande' },
  en: { suivi: 'Keep my accounts', creation: 'Start my company', filiale: 'Support my French subsidiary', autre: 'Other request' },
};
const FORM_TEXT = {
  fr: {
    subject: 'Demande de contact — Meyvin',
    success: 'Merci, votre demande a bien été envoyée. Nous revenons vers vous rapidement.',
    fallback: 'Nous n’avons pas pu envoyer votre message depuis le site. Votre messagerie s’ouvre avec votre demande préremplie : il vous reste à cliquer sur « Envoyer » dans votre messagerie, sinon votre message ne partira pas. Vous pouvez aussi écrire à contact@meyvin-experts.com.',
    labels: { name: 'Nom', email: 'E-mail', project: 'Projet', message: 'Message' },
  },
  en: {
    subject: 'Contact request — Meyvin',
    success: 'Thank you, your request has been sent. We will get back to you shortly.',
    fallback: 'We could not send your message from the site. Your email app is opening with your request pre-filled: you still need to click “Send” in your email app, otherwise your message will not leave. You can also write to contact@meyvin-experts.com.',
    labels: { name: 'Name', email: 'Email', project: 'Project', message: 'Message' },
  },
};
const setStatus = (text, state) => {
  if (!status) return;
  status.textContent = text;
  status.dataset.state = state || '';
  if (state) status.focus({ preventScroll: false });
};
// Opening the mail app is isolated here so it can be observed in tests.
const openMail = (url) => (window.rbOpenMail || ((u) => { window.location.href = u; }))(url);

if (form) {
  form.addEventListener('submit', async (e) => {
    e.preventDefault();
    if (!form.checkValidity()) { form.reportValidity(); return; }
    const data = new FormData(form);
    const lang = (window.rbI18n?.getLang?.() || document.documentElement.lang || 'fr') === 'en' ? 'en' : 'fr';
    const t = FORM_TEXT[lang];
    const project = PROJECTS[lang][data.get('project')] || PROJECTS[lang].autre;
    const subject = `${t.subject} · ${project}`;

    const submitBtn = form.querySelector('button[type="submit"]');
    const fallbackToMailto = () => {
      const c = lang === 'fr' ? ' : ' : ': ';
      const body = `${t.labels.name}${c}${data.get('name')}\n${t.labels.email}${c}${data.get('email')}\n${t.labels.project}${c}${project}\n\n${t.labels.message}${c.trim()}\n${data.get('message')}`;
      setStatus(window.rbI18n?.get?.('form.fallback') || t.fallback, 'fallback');
      openMail(`mailto:contact@meyvin-experts.com?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`);
    };

    if (submitBtn) submitBtn.disabled = true;
    try {
      const res = await fetch('https://formsubmit.co/ajax/contact@meyvin-experts.com', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', Accept: 'application/json' },
        body: JSON.stringify({
          name: data.get('name'),
          email: data.get('email'),
          [t.labels.project]: project,
          message: data.get('message'),
          _subject: subject,
          _replyto: data.get('email'),
          _template: 'table',
          _captcha: 'false',
        }),
      });
      // FormSubmit answers 200 with success:"false" while the address is not yet activated.
      const out = await res.json().catch(() => ({}));
      if (!res.ok || String(out.success).toLowerCase() === 'false') throw new Error('FormSubmit refused');
      setStatus(window.rbI18n?.get?.('form.success') || t.success, 'ok');
      form.reset();
    } catch (err) {
      fallbackToMailto();
    } finally {
      if (submitBtn) submitBtn.disabled = false;
    }
  });
}

