// Load Meyvin visual and structural upgrades
(() => {
  const here = document.currentScript?.src || '';
  const base = here ? here.replace(/js\/main\.js(?:\?.*)?$/, '') : '';
  const root = document.documentElement;
  const editorial = root.classList.contains('ed');
  const addCss = (href, onload) => {
    const link = document.createElement('link');
    link.rel = 'stylesheet';
    link.href = `${base}${href}`;
    if (onload) { link.onload = onload; link.onerror = onload; }
    document.head.appendChild(link);
  };
  const addJs = (src) => {
    const script = document.createElement('script');
    script.src = `${base}${src}`;
    document.head.appendChild(script);
    return script;
  };

  // Homepage: it carries its own layout and only needs the booking modal
  // and the motion layer from the shared scripts.
  if (root.hasAttribute('data-ed-home')) {
    addCss('css/final-polish.css');
    addJs('js/final-polish.js');
    addJs('js/ed-motion.js');
    return;
  }
  const css = document.createElement('link');
  css.rel = 'stylesheet';
  css.href = `${base}css/site-upgrade.css`;
  document.head.appendChild(css);

  // Final polish is intentionally loaded after the main upgrade stylesheet so
  // the narrow-card typography and booking/reassurance UI win the cascade.
  const polishCss = document.createElement('link');
  polishCss.rel = 'stylesheet';
  polishCss.href = `${base}css/final-polish.css`;
  document.head.appendChild(polishCss);

  const hotfixCss = document.createElement('link');
  hotfixCss.rel = 'stylesheet';
  hotfixCss.href = `${base}css/final-polish-hotfix.css`;
  document.head.appendChild(hotfixCss);

  const missionPolishCss = document.createElement('link');
  missionPolishCss.rel = 'stylesheet';
  missionPolishCss.href = `${base}css/mission-polish.css`;
  document.head.appendChild(missionPolishCss);

  const seoEnhanceCss = document.createElement('link');
  seoEnhanceCss.rel = 'stylesheet';
  seoEnhanceCss.href = `${base}css/seo-enhance.css`;
  document.head.appendChild(seoEnhanceCss);

  const internationalEnhanceCss = document.createElement('link');
  internationalEnhanceCss.rel = 'stylesheet';
  internationalEnhanceCss.href = `${base}css/international-enhance.css`;
  document.head.appendChild(internationalEnhanceCss);

  const homepagePolishCss = document.createElement('link');
  homepagePolishCss.rel = 'stylesheet';
  homepagePolishCss.href = `${base}css/homepage-polish.css`;
  document.head.appendChild(homepagePolishCss);

  const immersiveCss = document.createElement('link');
  immersiveCss.rel = 'stylesheet';
  immersiveCss.href = `${base}css/immersive.css`;
  document.head.appendChild(immersiveCss);

  // Editorial design. Loaded last so it re-skins every component above it.
  if (editorial) {
    addCss('css/editorial.css', () => root.classList.remove('ed-wait'));
    addJs('js/ed-motion.js');
  }

  const upgrade = document.createElement('script');
  upgrade.src = `${base}js/site-upgrade.js`;
  upgrade.onload = () => {
    document.querySelectorAll('#secteurs .reveal, #digital-ia .reveal, #faq .reveal').forEach((el) => el.classList.add('is-visible'));
    const upgradedNav = document.getElementById('nav');
    upgradedNav?.querySelectorAll('a').forEach((link) => link.addEventListener('click', () => {
      upgradedNav.classList.remove('is-open');
      document.getElementById('burger')?.setAttribute('aria-expanded', 'false');
    }));

    // Mission and internal-page content is generated by site-upgrade.js.
    // Notify the reveal system once the generated cards and blocks exist.
    document.dispatchEvent(new CustomEvent('rb:content-upgraded'));

    const polish = document.createElement('script');
    polish.src = `${base}js/final-polish.js`;
    polish.onload = () => {
      document.dispatchEvent(new CustomEvent('rb:content-upgraded'));
      const hotfix = document.createElement('script');
      hotfix.src = `${base}js/final-polish-hotfix.js`;
      hotfix.onload = () => document.dispatchEvent(new CustomEvent('rb:content-upgraded'));
      document.head.appendChild(hotfix);

      const seoEnhance = document.createElement('script');
      seoEnhance.src = `${base}js/seo-enhance.js`;
      document.head.appendChild(seoEnhance);

      const internationalEnhance = document.createElement('script');
      internationalEnhance.src = `${base}js/international-enhance.js`;
      document.head.appendChild(internationalEnhance);

      const revealSafety = document.createElement('script');
      revealSafety.src = `${base}js/reveal-safety.js`;
      document.head.appendChild(revealSafety);

      const homepagePolish = document.createElement('script');
      homepagePolish.src = `${base}js/homepage-polish.js`;
      document.head.appendChild(homepagePolish);

      const immersive = document.createElement('script');
      immersive.src = `${base}js/immersive.js`;
      document.head.appendChild(immersive);

      if (editorial) addJs('js/editorial.js');
    };
    document.head.appendChild(polish);
  };
  document.head.appendChild(upgrade);
})();

